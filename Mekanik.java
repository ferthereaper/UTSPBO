package UTS;

public class Mekanik {
    private String nama;
    private String spesialisasi;

    public Mekanik(String nama, String spesialisasi) {
        this.nama = nama;
        this.spesialisasi = spesialisasi;
    }

    public String getNama() {
        return nama;
    }

    public String getSpesial() {
        return spesialisasi;
    }
}